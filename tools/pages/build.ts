/**
 * Build the colouring pages: tools/pages/scenes.ts → src/coloring/pages/level{1..4}.ts + index.ts,
 * tools/pages/svgs/ (offline copy of the Pastelki SVGs used) and assets/pages-contact-sheet-l{1..4}.png.
 *
 *   npm run build-pages              # offline: uses the committed tools/pages/svgs/ copy where present
 *   npm run build-pages -- --refresh # re-fetch the Pastelki library + SVGs (newest approved versions)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import type { Level, Page } from '../../src/coloring/types';
import { buildPage } from './compose';
import { Library } from './library';
import { SCENES } from './scenes';
import { contactSheet } from './sheet';

const ROOT = join(__dirname, '../..');
const OUT = join(ROOT, 'src/coloring/pages');
const LEVELS: Level[] = [1, 2, 3, 4];

const difficulty = (p: Page) => p.regions * 1000 + p.shapes.length;

async function main() {
  const refresh = process.argv.includes('--refresh');
  const lib = new Library(refresh);
  await lib.load();
  mkdirSync(OUT, { recursive: true });
  let total = 0;
  for (const level of LEVELS) {
    const pages: Page[] = [];
    for (const spec of SCENES[level]) {
      const { page, warnings } = await buildPage(lib, level, spec);
      for (const w of warnings) console.warn(`  ! ${page.id}: ${w}`);
      pages.push(page);
    }
    pages.sort((a, b) => difficulty(a) - difficulty(b));
    const ids = new Set<string>();
    for (const p of pages) {
      if (ids.has(p.id)) throw new Error(`duplicate id ${p.id}`);
      ids.add(p.id);
    }
    const src =
      `/** GENERATED by tools/pages (npm run build-pages) — do not edit. Level ${level}, ${pages.length} pages. Pictures: Pastelki (MIT). */\n` +
      `import type { Page } from '../types';\n\n` +
      `export const LEVEL${level}: Page[] = ${JSON.stringify(pages)};\n`;
    writeFileSync(join(OUT, `level${level}.ts`), src);
    total += src.length;
    console.log(`level ${level}: ${pages.length} pages, ${(src.length / 1024).toFixed(0)} KB — ${pages.map((p) => `${p.id}(${p.regions})`).join(' ')}`);
    contactSheet(pages, join(ROOT, `assets/pages-contact-sheet-l${level}.png`));
    contactSheet(pages, join(ROOT, `assets/pages-contact-sheet-l${level}-regions.png`), { mode: 'regions', cols: 4 });
  }
  writeFileSync(
    join(OUT, 'index.ts'),
    `/** GENERATED by tools/pages (npm run build-pages) — the page catalogue. */\n` +
      `import type { Level, Page } from '../types';\n` +
      LEVELS.map((l) => `import { LEVEL${l} } from './level${l}';\n`).join('') +
      `\nexport const PAGES: Page[] = [${LEVELS.map((l) => `...LEVEL${l}`).join(', ')}];\n\n` +
      `export const pagesOfLevel = (level: Level): Page[] => PAGES.filter((p) => p.level === level);\n` +
      `export const getPage = (id: string): Page | undefined => PAGES.find((p) => p.id === id);\n`,
  );
  lib.saveCommitted();
  console.log(`total ${(total / 1024).toFixed(0)} KB generated; ${lib.used.size} Pastelki SVGs in tools/pages/svgs/`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
